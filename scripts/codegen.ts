import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { compileContent } from "./lib/compile.js";
import {
  Collector,
  ValidationFailure,
  formatValidationError,
} from "./lib/errors.js";
import { loadContent, REPO_ROOT } from "./lib/load.js";

function generate(): void {
  const collector = new Collector();
  const raw = loadContent(collector);
  let output;
  try {
    output = compileContent(raw, collector);
  } catch (error) {
    if (error instanceof ValidationFailure) {
      for (const validationError of error.errors) {
        console.error(formatValidationError(validationError));
      }
      process.exit(1);
    }
    throw error;
  }

  const runtimePath = join(REPO_ROOT, "src", "generated", "runtime.ts");
  const validationPath = join(REPO_ROOT, "tests", "generated", "validation.ts");

  const runtimeSource = [
    "// AUTO-GENERATED by scripts/codegen.ts. Do not edit by hand.",
    "// Contains active content only. Reference solutions are never emitted here.",
    'import type { CompiledCompatibility, CompiledRuntime } from "../internal/data.js";',
    "",
    `export const RUNTIME: CompiledRuntime = ${JSON.stringify(output.runtime, null, 2)};`,
    "",
    `export const COMPATIBILITY: CompiledCompatibility = ${JSON.stringify(output.compatibility, null, 2)};`,
    "",
    `export const CONTENT_BUILD_ID = ${JSON.stringify(output.buildId)};`,
    "",
  ].join("\n");

  const validationSource = [
    "// AUTO-GENERATED by scripts/codegen.ts. CI-only; never published.",
    "// Contains reference solutions for replay tests.",
    "export interface ValidationTemplate {",
    "  readonly templateId: string;",
    "  readonly lessonId: string;",
    "  readonly status: string;",
    "  readonly engineRange: string;",
    "  readonly solution: readonly string[];",
    "  readonly par: number;",
    "}",
    "",
    `export const VALIDATION: readonly ValidationTemplate[] = ${JSON.stringify(
      Object.keys(output.solutions)
        .sort()
        .map((templateId) => {
          const template = output.runtime.templates.find(
            (item) => item.id === templateId,
          );
          return {
            templateId,
            lessonId: template?.lessonId ?? "",
            status: template === undefined ? "draft" : "active",
            engineRange: output.engineRanges[templateId] ?? "",
            solution: output.solutions[templateId] ?? [],
            par: template?.par ?? 0,
          };
        }),
      null,
      2,
    )};`,
    "",
  ].join("\n");

  mkdirSync(join(REPO_ROOT, "src", "generated"), { recursive: true });
  mkdirSync(join(REPO_ROOT, "tests", "generated"), { recursive: true });
  writeFileSync(runtimePath, runtimeSource, "utf8");
  writeFileSync(validationPath, validationSource, "utf8");

  console.log(
    `codegen: ${output.runtime.skills.length} skills, ` +
      `${output.runtime.lessons.length} lessons, ` +
      `${output.runtime.templates.length} templates, ` +
      `build ${output.buildId.slice(0, 12)}`,
  );
}

generate();
